    private void btnApproveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApproveActionPerformed
    

    int row = tblRequests.getSelectedRow();

    if(row == -1){
        JOptionPane.showMessageDialog(this,
                "Select a request.");
        return;
    }

    int requestId =
            Integer.parseInt(tblRequests.getValueAt(row,0).toString());

    int studentId =
            Integer.parseInt(tblRequests.getValueAt(row,1).toString());

    try{

        Connection conn = DBConnection.getConnection();

        String sql =
                "UPDATE loan_requests SET status='Approved' WHERE request_id=?";

        PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setInt(1, requestId);

        pst.executeUpdate();

        String notify =
 
"INSERT INTO notifications(user_id,message,status) VALUES(?,?,?)";

        PreparedStatement pst2 =
                conn.prepareStatement(notify);

        pst2.setInt(1, studentId);
        pst2.setString(2,
                " Congratulations your laptop request has been ACCEPTED.");
        pst2.setString(3,"Unread");

        pst2.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Request APPROVED.");

        loadRequests();

    }catch(Exception ex){

        JOptionPane.showMessageDialog(this,
                ex.getMessage());

    }


                                             

    


   

    


         
    }//GEN-LAST:event_btnApproveActionPerformed

