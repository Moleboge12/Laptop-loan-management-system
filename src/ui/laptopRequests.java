    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
                                          
  

    String studentID = txtStudentID.getText();
    String studentName = txtStudentName.getText();
    String laptop = cmblaptop.getSelectedItem().toString();
    String duration = cmblaptop.getSelectedItem().toString();
    String reason = txtReason.getText();

    if(studentID.isEmpty() || studentName.isEmpty() || reason.isEmpty()){
        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    try{
        Connection conn = DBConnection.getConnection();

        String sql = "INSERT INTO loan_requests(student_id, student_name, laptop_model, duration, reason, status) VALUES(?,?,?,?,?,?)";

        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, studentID);
        pst.setString(2, studentName);
        pst.setString(3, laptop);
        pst.setString(4, duration);
        pst.setString(5, reason);
        pst.setString(6, "Pending");

        int rows = pst.executeUpdate();

        if(rows > 0){

            JOptionPane.showMessageDialog(this,
                    "Loan Request Submitted Successfully!");

            txtReason.setText("");
            cmblaptop.setSelectedIndex(0);
            cmblaptop.setSelectedIndex(0);

        }else{

            JOptionPane.showMessageDialog(this,
                    "Failed to submit request.");

        }

        pst.close();
        conn.close();

    }catch(Exception e){

        JOptionPane.showMessageDialog(this, e.getMessage());

    }




    }//GEN-LAST:event_btnSubmitActionPerformed

