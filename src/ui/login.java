    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
          
 try{
     
        Connection conn = DBConnection.getConnection();
if (conn == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database connection failed.");
        return; // stop here if no connection
    }
            String sql = "SELECT * FROM users WHERE id = ? AND password = ? AND role = ?";
            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setInt(1, Integer.parseInt(txtID.getText().trim()));
            pst.setString(2, new String(txtPassword.getText()).trim());
            pst.setString(3, cmbrole.getSelectedItem().toString().trim());

            ResultSet rs = pst.executeQuery();

               if (rs.next()) {
        String role = rs.getString("role");
        JOptionPane.showMessageDialog(this, " Login successful!");

        if ("Admin".equalsIgnoreCase(role)) {

    new adminDashboard1().setVisible(true);

} else if ("Student".equalsIgnoreCase(role)) {

    int studentId = rs.getInt("id");
    String fullname = rs.getString("fullname");

    new StudentDashboard(fullname, studentId).setVisible(true);

}

this.dispose();
    } else {
        JOptionPane.showMessageDialog(this, " Invalid ID, password or role");
    }

    DBConnection.closeConnection();

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}               
   

     
    }//GEN-LAST:event_btnLoginActionPerformed

