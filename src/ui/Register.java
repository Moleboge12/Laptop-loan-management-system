    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    
                                        
        try {
            // Validation
            if (txtName.getText().trim().isEmpty() ||
                txtID.getText().trim().isEmpty() ||
                txtPassword.getText().length() == 0 ||
                txtConfirmPassword.getText().length() == 0 ||
                cmbRole.getSelectedIndex() == 0) {
                
                JOptionPane.showMessageDialog(this, "⚠️ Please fill in all fields.");
                return;
            }

            if (!txtID.getText().matches("\\d{6}")) {
                JOptionPane.showMessageDialog(this, "⚠️ Student number must be exactly 6 digits.");
                return;
            }

            String password = new String(txtPassword.getText()).trim();
            String confirmPassword = new String(txtConfirmPassword.getText()).trim();

            if (!password.equals(confirmPassword)) {
                JOptionPane.showMessageDialog(this, "⚠️ Passwords do not match.");
                return;
            }

            String strongRegex = "^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d)(?=.*[@$!%*?&]).{8,}$";
            if (!password.matches(strongRegex)) {
                JOptionPane.showMessageDialog(this, "⚠️ Password must be strong.");
                return;
            }

            // Insert into DB (5 columns)
            Connection conn = DBConnection.getConnection();
            String sql = "INSERT INTO users(id, fullname, password, role, confirmPassword) VALUES (?,?,?,?,?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, Integer.parseInt(txtID.getText().trim())); // student number as ID
            pst.setString(2, txtName.getText().trim());
            pst.setString(3, password);
            pst.setString(4, cmbRole.getSelectedItem().toString().trim());
            pst.setString(5, confirmPassword);

            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, " Registered successfully!");

            DBConnection.closeConnection();

            // Always redirect to Login after registration
            this.dispose();
            new login().setVisible(true);

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
                                              


    

     
     
    }//GEN-LAST:event_jButton1ActionPerformed

